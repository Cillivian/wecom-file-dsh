/**
 * Generate the standalone `--patch` overlay for `dsh web` with this checkout's
 * absolute path, so no machine-specific path is committed.
 *
 * Caveat: a patch overlay only resolves `@deepseek-ai/*` for plugin paths
 * inside the profile tree or its linked roots. Prefer installing the package as
 * a profile bundle (see docs/SETUP.md); this overlay is for local iteration
 * against a checkout that is already linked.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const entry = join(ROOT, 'src', 'host', 'index.ts')
const target = join(ROOT, 'cordis.dev.yml')

writeFileSync(target, `# Generated by tools/dev-patch.mjs — edit cordis.yml instead.
- insert:
    - id: wecom-picker
      name: ${JSON.stringify(entry)}
`)
console.log(`dev-patch: wrote ${target}`)
